// TEMPORARY migration helper: full logical SQL dump via the app's pg pool.
// Activated only when OCS_DUMP_SECRET is set; remove after migration.
'use strict';

function qIdent(s) { return '"' + String(s).replace(/"/g, '""') + '"'; }
function lit(v, typ) {
  if (v === null || v === undefined) return 'NULL';
  const t = String(typ || '').toLowerCase();
  if (t === 'json' || t === 'jsonb') {
    return "'" + JSON.stringify(v).replace(/'/g, "''") + "'::" + t;
  }
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  if (typeof v === 'number' && Number.isFinite(v)) return String(v);
  if (typeof v === 'bigint') return String(v);
  if (v instanceof Date) return "'" + v.toISOString().replace(/'/g, "''") + "'";
  if (Buffer.isBuffer(v)) return "'\\x" + v.toString('hex') + "'";
  if (typeof v === 'object') return "'" + JSON.stringify(v).replace(/'/g, "''") + "'";
  if (t.startsWith('timestamp') || t === 'date' || t === 'time' || t.startsWith('time ')) {
    return "'" + String(v).replace(/'/g, "''") + "'::" + typ;
  }
  if (t === 'uuid') return "'" + String(v).replace(/'/g, "''") + "'::uuid";
  return "'" + String(v).replace(/'/g, "''") + "'";
}

async function logicalDump(pool) {
  const out = [];
  out.push('-- OCS logical dump ' + new Date().toISOString());
  out.push('SET client_encoding = \'UTF8\';');
  out.push('SET standard_conforming_strings = on;');
  out.push('SET session_replication_role = replica;'); // relax FKs during load
  out.push('BEGIN;');

  const schemas = await pool.query(`SELECT nspname FROM pg_namespace
    WHERE nspname NOT IN ('pg_catalog','information_schema','pg_toast')
      AND nspname NOT LIKE 'pg_%' ORDER BY 1`);
  for (const { nspname } of schemas.rows) out.push(`CREATE SCHEMA IF NOT EXISTS ${qIdent(nspname)};`);

  // Sequences before tables (SERIAL defaults reference them)
  const seqsEarly = await pool.query(`
    SELECT n.nspname AS schema, c.relname AS name,
           s.seqstart, s.seqincrement, s.seqmax, s.seqmin, s.seqcache, s.seqcycle
    FROM pg_class c
    JOIN pg_namespace n ON n.oid=c.relnamespace
    JOIN pg_sequence s ON s.seqrelid=c.oid
    WHERE c.relkind='S' AND n.nspname NOT IN ('pg_catalog','information_schema')
      AND n.nspname NOT LIKE 'pg_%'
    ORDER BY 1,2`);
  for (const s of seqsEarly.rows) {
    const fq = `${qIdent(s.schema)}.${qIdent(s.name)}`;
    out.push(`CREATE SEQUENCE IF NOT EXISTS ${fq} AS bigint INCREMENT BY ${s.seqincrement} MINVALUE ${s.seqmin} MAXVALUE ${s.seqmax} START WITH ${s.seqstart} CACHE ${s.seqcache}${s.seqcycle ? ' CYCLE' : ' NO CYCLE'};`);
  }

  const tables = await pool.query(`
    SELECT n.nspname AS schema, c.relname AS name, c.oid
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE c.relkind='r' AND n.nspname NOT IN ('pg_catalog','information_schema','pg_toast')
      AND n.nspname NOT LIKE 'pg_%'
    ORDER BY n.nspname, c.relname`);

  for (const t of tables.rows) {
    const cols = await pool.query(`
      SELECT a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod) AS typ,
             a.attnotnull, pg_get_expr(ad.adbin, ad.adrelid) AS def,
             a.attidentity, a.attgenerated
      FROM pg_attribute a
      LEFT JOIN pg_attrdef ad ON ad.adrelid=a.attrelid AND ad.adnum=a.attnum
      WHERE a.attrelid=$1 AND a.attnum>0 AND NOT a.attisdropped
      ORDER BY a.attnum`, [t.oid]);
    const parts = [];
    for (const c of cols.rows) {
      let line = qIdent(c.attname) + ' ' + c.typ;
      if (c.attidentity === 'a') line += ' GENERATED ALWAYS AS IDENTITY';
      else if (c.attidentity === 'd') line += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (c.attgenerated === 's' && c.def) line += ' GENERATED ALWAYS AS (' + c.def + ') STORED';
      else if (c.def) line += ' DEFAULT ' + c.def;
      if (c.attnotnull) line += ' NOT NULL';
      parts.push(line);
    }
    out.push(`CREATE TABLE IF NOT EXISTS ${qIdent(t.schema)}.${qIdent(t.name)} (\n  ${parts.join(',\n  ')}\n);`);
  }

  const cons = await pool.query(`
    SELECT n.nspname AS schema, c.relname AS tbl, con.conname, con.contype,
           pg_get_constraintdef(con.oid, true) AS def
    FROM pg_constraint con
    JOIN pg_class c ON c.oid=con.conrelid
    JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname NOT LIKE 'pg_%'
      AND con.contype IN ('p','u','c','f')
    ORDER BY CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'f' THEN 3 END,
             n.nspname, c.relname, con.conname`);
  for (const r of cons.rows) {
    out.push(`DO $$ BEGIN ALTER TABLE ${qIdent(r.schema)}.${qIdent(r.tbl)} ADD CONSTRAINT ${qIdent(r.conname)} ${r.def}; EXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
  }

  const idxs = await pool.query(`
    SELECT schemaname, indexname, indexdef FROM pg_indexes
    WHERE schemaname NOT IN ('pg_catalog','information_schema') AND schemaname NOT LIKE 'pg_%'
      AND indexname NOT IN (SELECT conname FROM pg_constraint WHERE conname IS NOT NULL)
    ORDER BY 1,2`);
  for (const i of idxs.rows) {
    let def = i.indexdef;
    if (!/IF NOT EXISTS/i.test(def)) def = def.replace(/^CREATE (UNIQUE )?INDEX/i, 'CREATE $1INDEX IF NOT EXISTS');
    out.push(def + ';');
  }

  const counts = {};
  out.push('-- data');
  for (const t of tables.rows) {
    const cols = await pool.query(`
      SELECT a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod) AS typ
      FROM pg_attribute a
      WHERE a.attrelid=$1 AND a.attnum>0 AND NOT a.attisdropped
        AND COALESCE(a.attgenerated,'') = ''
      ORDER BY a.attnum`, [t.oid]);
    const colNames = cols.rows.map(c => c.attname);
    const colTyps = cols.rows.map(c => c.typ);
    const fq = `${qIdent(t.schema)}.${qIdent(t.name)}`;
    const res = await pool.query(`SELECT * FROM ${fq}`);
    const key = t.schema + '.' + t.name;
    counts[key] = res.rowCount;
    out.push(`-- ${key}: ${res.rowCount} rows`);
    if (!res.rowCount) continue;
    const colList = colNames.map(qIdent).join(', ');
    for (const row of res.rows) {
      const vals = colNames.map((n, i) => lit(row[n], colTyps[i]));
      out.push(`INSERT INTO ${fq} (${colList}) VALUES (${vals.join(', ')});`);
    }
  }

  const seqs = await pool.query(`
    SELECT n.nspname AS schema, c.relname AS name
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE c.relkind='S' AND n.nspname NOT IN ('pg_catalog','information_schema')
      AND n.nspname NOT LIKE 'pg_%' ORDER BY 1,2`);
  for (const s of seqs.rows) {
    const fq = `${qIdent(s.schema)}.${qIdent(s.name)}`;
    const v = await pool.query(`SELECT last_value, is_called FROM ${fq}`);
    const row = v.rows[0];
    out.push(`SELECT setval(pg_catalog.quote_ident('${s.schema}') || '.' || pg_catalog.quote_ident('${s.name}'), ${Number(row.last_value)}, ${row.is_called});`);
  }

  out.push('SET session_replication_role = DEFAULT;');
  out.push('COMMIT;');
  const sql = out.join('\n') + '\n';
  return { sql, counts };
}

function mountDumpRoute(app, getPool) {
  const secret = String(process.env.OCS_DUMP_SECRET || '').trim();
  if (!secret) return false;
  app.get('/api/__temp_db_dump', async (req, res) => {
    const auth = String(req.headers.authorization || '');
    const token = auth.toLowerCase().startsWith('bearer ') ? auth.slice(7).trim() : String(req.headers['x-ocs-dump-token'] || '');
    if (!token || token !== secret) {
      res.status(401).type('text').send('unauthorized');
      return;
    }
    const pool = typeof getPool === 'function' ? getPool() : getPool;
    if (!pool) {
      res.status(503).type('text').send('no postgres pool');
      return;
    }
    try {
      const { sql, counts } = await logicalDump(pool);
      res.setHeader('X-OCS-Dump-Counts', Buffer.from(JSON.stringify(counts)).toString('base64'));
      res.setHeader('Content-Type', 'application/sql; charset=utf-8');
      res.setHeader('Content-Disposition', 'attachment; filename="ocs-db-backup.sql"');
      res.send(sql);
    } catch (e) {
      console.error('[temp-dump] failed:', e && e.message);
      res.status(500).type('text').send('dump failed');
    }
  });
  console.log('[temp-dump] /api/__temp_db_dump mounted (secret set)');
  return true;
}


function mountRestoreRoute(app, getPool) {
  const secret = String(process.env.OCS_DUMP_SECRET || '').trim();
  if (!secret) return false;
  app.post('/api/__temp_db_restore', async (req, res) => {
    const auth = String(req.headers.authorization || '');
    const token = auth.toLowerCase().startsWith('bearer ') ? auth.slice(7).trim() : String(req.headers['x-ocs-dump-token'] || '');
    if (!token || token !== secret) {
      res.status(401).type('text').send('unauthorized');
      return;
    }
    const pool = typeof getPool === 'function' ? getPool() : getPool;
    if (!pool) {
      res.status(503).type('text').send('no postgres pool');
      return;
    }
    const chunks = [];
    try {
      await new Promise((resolve, reject) => {
        req.on('data', (c) => chunks.push(c));
        req.on('end', resolve);
        req.on('error', reject);
      });
      const sql = Buffer.concat(chunks).toString('utf8');
      if (!sql || sql.length < 20) {
        res.status(400).type('text').send('empty sql');
        return;
      }
      const client = await pool.connect();
      try {
        await client.query(sql);
        const tables = await client.query(`
          SELECT n.nspname AS schema, c.relname AS name
          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
          WHERE c.relkind = 'r' AND n.nspname NOT IN ('pg_catalog','information_schema')
          ORDER BY 1,2`);
        const counts = {};
        for (const t of tables.rows) {
          const r = await client.query(`SELECT count(*)::int AS n FROM "${t.schema}"."${t.name}"`);
          counts[`${t.schema}.${t.name}`] = r.rows[0].n;
        }
        res.json({ ok: true, bytes: sql.length, counts });
      } finally {
        client.release();
      }
    } catch (e) {
      console.error('[temp-restore] failed:', e && e.message);
      res.status(500).type('text').send('restore failed: ' + String(e && e.message || e).slice(0, 200));
    }
  });
  console.log('[temp-dump] /api/__temp_db_restore mounted (secret set)');
  return true;
}

module.exports = { logicalDump, mountDumpRoute, mountRestoreRoute };
